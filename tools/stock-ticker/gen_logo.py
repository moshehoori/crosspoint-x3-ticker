"""Usage: gen_logo.py in.svg out.h width Name. Rasterize a logo SVG to a 1-bit C header for CrossPoint (bit=1 is ink, MSB-first, row-major)."""
import subprocess, sys
from PIL import Image

svg, out, width, name = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4]
UP = name.upper()
png = out + ".png"
subprocess.run(["convert", "-background", "white", "-density", "1200", svg, "-resize", f"{width}x",
                "-flatten", png], check=True)
im = Image.open(png).convert("RGB")
w, h = im.size
rows, row_bytes = [], (w + 7) // 8
for y in range(h):
    row = bytearray(row_bytes)
    for x in range(w):
        r, g, b = im.getpixel((x, y))
        if (r + g + b) / 3 < 200:  # any colored (blue) pixel becomes ink
            row[x >> 3] |= 0x80 >> (x & 7)
    rows.append(row)
data = b"".join(rows)
with open(out, "w") as f:
    f.write("#pragma once\n#include <cstdint>\n\n")
    f.write(f"// {name} logo, 1bpp, MSB-first, row-major, bit==1 = ink. Generated by gen_logo.py.\n")
    f.write(f"static constexpr int {UP}_LOGO_W = {w};\nstatic constexpr int {UP}_LOGO_H = {h};\n")
    f.write(f"static const uint8_t {name}Logo[] = {{\n")
    for i in range(0, len(data), 19):
        f.write("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 19]) + ",\n")
    f.write("};\n")
# preview
prev = Image.new("1", (w, h), 1)
for y in range(h):
    for x in range(w):
        if rows[y][x >> 3] & (0x80 >> (x & 7)):
            prev.putpixel((x, y), 0)
prev.save(out + ".preview.png")
print(w, h, len(data), "bytes")
